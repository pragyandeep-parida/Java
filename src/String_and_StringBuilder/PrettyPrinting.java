package String_and_StringBuilder;

public class PrettyPrinting
{
    public static void main(String[] args)
    {
        float a = 123.1234f;

        System.out.printf("The formatted value is %.2f",a);

        System.out.println();

        System.out.printf("pi value : %.3f", Math.PI);

        System.out.println();

        System.out.printf("Hello my name is %s and my title is %s", "pragyandeep", "parida");  // check format specifier types.txt

        System.out.println();

        char c = 'd';
        System.out.printf("The the character is  %c ",c);

    }
}
